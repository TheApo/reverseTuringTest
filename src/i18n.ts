export const DICT: Record<Lang, Record<Key, string>> = { de, en }
const inBrowser = typeof document !== 'undefined' // Tests laufen ohne Browser
const browserLang = (): Lang => (navigator.language.toLowerCase().startsWith('de') ? 'de' : 'en')
let lang: Lang = inBrowser ? (localStorage.getItem('rtt-lang') as Lang | null) ?? browserLang() : 'de'
if (inBrowser) document.documentElement.lang = lang

export const getLang = () => lang

/** persist=false für den Beamer: Er folgt der Spielsprache, ohne die Wahl im Browser zu speichern. */
export function setLang(next: Lang, persist = true) {
  if (persist) localStorage.setItem('rtt-lang', next)
  if (next === lang) return
  lang = next
  document.documentElement.lang = next
  if (persist) dispatchEvent(new Event('rtt-prefs'))
}

export function t(key: Key, vars: Record<string, string | number> = {}) {
  return (DICT[lang][key] ?? key).replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ''))
}

/** Plural über die Keys `…_one` / `…_other`, {n} ist automatisch gesetzt. */
export const tn = (key: Plural, n: number, vars: Record<string, string | number> = {}) =>
  t(`${key}_${n === 1 ? 'one' : 'other'}` as Key, { n, ...vars })

/** Für Fehler-Keys vom Server, die nicht im Wörterbuch stehen könnten. */
export const tError = (key: string) => (key in de ? t(key as Key) : key)

/** Rendert die App neu, wenn Sprache oder Design umgeschaltet werden. */
export function usePrefs() {
  const [, bump] = useReducer((x: number) => x + 1, 0)
  useEffect(() => {
    addEventListener('rtt-prefs', bump)
    return () => removeEventListener('rtt-prefs', bump)
  }, [])
}
